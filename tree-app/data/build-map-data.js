// Builds data/world-data.js for the offline Map View.
// Inputs (public datasets, downloaded once into <inputDir>):
//   countries.json   Natural Earth 110m admin-0 countries GeoJSON (public domain)
//   cities15000.txt  GeoNames cities with population > 15,000 (CC BY 4.0)
//   admin1.txt       GeoNames admin1CodesASCII.txt (CC BY 4.0)
// Usage: node build-map-data.js <inputDir>
const fs = require('fs');
const path = require('path');

const inputDir = process.argv[2];
if (!inputDir) { console.error('Usage: node build-map-data.js <inputDir>'); process.exit(1); }
const read = (name) => fs.readFileSync(path.join(inputDir, name), 'utf8');
const round = (n, digits) => Number(n.toFixed(digits));

const geo = JSON.parse(read('countries.json'));
const countries = [];
for (const feature of geo.features) {
  const props = feature.properties;
  if (props.ADMIN === 'Antarctica') continue;
  const polygons = feature.geometry.type === 'Polygon' ? [feature.geometry.coordinates] : feature.geometry.coordinates;
  const rings = [];
  let best = null;
  for (const polygon of polygons) {
    const outer = [];
    for (const [lon, lat] of polygon[0]) {
      const point = [round(lon, 1), round(lat, 1)];
      const last = outer[outer.length - 1];
      if (!last || last[0] !== point[0] || last[1] !== point[1]) outer.push(point);
    }
    if (outer.length < 3) continue;
    rings.push(outer.flat());
    let area = 0; let cx = 0; let cy = 0;
    for (let i = 0; i < outer.length; i += 1) {
      const [x1, y1] = outer[i]; const [x2, y2] = outer[(i + 1) % outer.length];
      const cross = x1 * y2 - x2 * y1;
      area += cross; cx += (x1 + x2) * cross; cy += (y1 + y2) * cross;
    }
    area /= 2;
    if (!best || Math.abs(area) > Math.abs(best.area)) best = { area, c: area ? [cy / (6 * area), cx / (6 * area)] : [outer[0][1], outer[0][0]] };
  }
  const names = new Set([props.ADMIN, props.NAME, props.NAME_LONG, props.FORMAL_EN, props.ABBREV, props.NAME_EN].filter(Boolean));
  countries.push({
    n: props.NAME_LONG || props.NAME, a2: props.ISO_A2_EH, a3: props.ISO_A3_EH,
    al: [...names], c: best ? [round(best.c[0], 2), round(best.c[1], 2)] : [0, 0], p: rings
  });
}

const adminNames = new Map();
for (const line of read('admin1.txt').split(/\r?\n/)) {
  const [code, name, ascii] = line.split('\t');
  if (code) adminNames.set(code, ascii || name);
}

const cities = [];
const adminAccumulator = new Map();
for (const line of read('cities15000.txt').split(/\r?\n/)) {
  if (!line) continue;
  const f = line.split('\t');
  const [name, ascii, lat, lon, cc, admin1, pop] = [f[1], f[2], Number(f[4]), Number(f[5]), f[8], f[10], Number(f[14])];
  cities.push([name, ascii === name ? '' : ascii, round(lat, 2), round(lon, 2), cc, admin1, pop]);
  const key = `${cc}.${admin1}`;
  if (admin1 && adminNames.has(key)) {
    const weight = Math.sqrt(pop || 1);
    const entry = adminAccumulator.get(key) || { w: 0, lat: 0, lon: 0 };
    entry.w += weight; entry.lat += lat * weight; entry.lon += lon * weight;
    adminAccumulator.set(key, entry);
  }
}
const admin1 = {};
for (const [key, entry] of adminAccumulator) admin1[key] = [adminNames.get(key), round(entry.lat / entry.w, 2), round(entry.lon / entry.w, 2)];

const output = `// Generated by build-map-data.js. Do not edit.
// Country outlines: Natural Earth (public domain). Places: GeoNames, https://www.geonames.org (CC BY 4.0).
window.KINSHIP_GEO = ${JSON.stringify({ countries, admin1, cities })};
`;
fs.writeFileSync(path.join(__dirname, 'world-data.js'), output);
console.log(`countries=${countries.length} admin1=${Object.keys(admin1).length} cities=${cities.length} size=${(output.length / 1024).toFixed(0)}KB`);
