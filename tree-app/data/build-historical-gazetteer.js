// Builds data/historical-gazetteer.js from the three editable JSON files in
// this folder (historical-gazetteer.json, place-aliases.json, historical-regions.json).
// The app loads the generated bundle; the JSON files are the source of truth
// and are also used by the Tools > Historical Gazetteer import/export feature.
// Usage: node build-historical-gazetteer.js
const fs = require('fs');
const path = require('path');

const dir = __dirname;
const readJson = (name) => JSON.parse(fs.readFileSync(path.join(dir, name), 'utf8'));

const gazetteer = readJson('historical-gazetteer.json');
const aliases = readJson('place-aliases.json');
const regions = readJson('historical-regions.json');

// Sanity checks: every alias must point somewhere resolvable, every gazetteer
// entry needs coordinates.
for (const [name, entry] of Object.entries(gazetteer)) {
  if (typeof entry.latitude !== 'number' || typeof entry.longitude !== 'number') {
    throw new Error(`historical-gazetteer.json: "${name}" has no valid coordinates.`);
  }
}
for (const [alias, target] of Object.entries(aliases)) {
  if (alias === target) throw new Error(`place-aliases.json: "${alias}" maps to itself.`);
}
for (const [name, entry] of Object.entries(regions)) {
  if (typeof entry.latitude !== 'number' || typeof entry.longitude !== 'number') {
    throw new Error(`historical-regions.json: "${name}" has no valid coordinates.`);
  }
}

// Aliases may point at another alias (transitive chains). They are resolved
// here so the runtime lookup stays a single map read.
const resolvedAliases = {};
for (const [alias, target] of Object.entries(aliases)) {
  let end = target;
  const seen = new Set([alias]);
  while (gazetteer[end] === undefined && aliases[end] !== undefined && !seen.has(end)) {
    seen.add(end);
    end = aliases[end];
  }
  resolvedAliases[alias] = end;
}

const output = `// Generated by build-historical-gazetteer.js. Do not edit — edit the JSON files in
// data/ and rerun the build. Sources: World Historical Gazetteer (WHG), Getty TGN and
// GeoNames alternate names, curated for genealogy research 1700-1970.
window.KINSHIP_HISTORICAL_GAZETTEER = {
  places: ${JSON.stringify(gazetteer)},
  aliases: ${JSON.stringify(resolvedAliases)},
  regions: ${JSON.stringify(regions)}
};
`;
fs.writeFileSync(path.join(dir, 'historical-gazetteer.js'), output);
console.log(`places=${Object.keys(gazetteer).length} aliases=${Object.keys(resolvedAliases).length} regions=${Object.keys(regions).length} size=${(output.length / 1024).toFixed(0)}KB`);
